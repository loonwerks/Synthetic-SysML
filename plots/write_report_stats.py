#!/usr/bin/env python3
"""Write exact aggregate tables that support interpretation of the figures."""

from __future__ import annotations

import json
import statistics
from collections import Counter, defaultdict
from pathlib import Path


HERE = Path(__file__).resolve().parent
DATA = HERE / "analysis-data.json"
OUT = HERE / "REPORT_STATS.md"
TIERS = ("small", "medium", "hard")
VERDICTS = ("EQUIVALENT", "CANDIDATE_WEAKER", "INCOMPARABLE", "INCONCLUSIVE", "INVALID_INPUT")


def median(values):
    values = [value for value in values if value is not None]
    return statistics.median(values) if values else None


def fmt(value, decimals=1):
    if value is None:
        return "n/a"
    return f"{value:,.{decimals}f}"


def main():
    payload = json.loads(DATA.read_text(encoding="utf-8"))
    generation = payload["generation"]
    scp = {row["dataset_id"]: row for row in payload["scp"]}
    poolside = {row["dataset_id"]: row for row in payload["poolside"]}
    campaign = generation
    lines = [
        "# Exact statistics supporting the plot suite", "",
        "Generated by `python3 plots/write_report_stats.py` from `plots/analysis-data.json`.", "",
        "## Corpus and tier summary", "",
        "The reported corpus contains only the 48 seed-derived campaign instances (8 families × 3 tiers × 2 diverse replicates). Four legacy systems are excluded.", "",
        "| Tier | N | Semantic usages | Interactions | Contract cases | Scenarios | Formal clauses | Generation min | Generation tokens | Terra gate-qualified | Equivalent | Weaker | Terra min | Terra input+output tokens |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for tier in TIERS:
        rows = [row for row in campaign if row["difficulty"] == tier]
        sruns = [scp[row["dataset_id"]] for row in rows]
        lines.append(
            f"| {tier.title()} | {len(rows)} | "
            f"{fmt(median([r['complexity']['semantic_usages'] for r in rows]))} | "
            f"{fmt(median([r['complexity']['semantic_interactions'] for r in rows]))} | "
            f"{fmt(median([r['complexity']['nontrivial_contract_cases'] for r in rows]))} | "
            f"{fmt(median([r['complexity']['scenario_families'] for r in rows]))} | "
            f"{fmt(median([r['published']['formal_clauses'] for r in rows]))} | "
            f"{fmt(median([r['generation']['elapsed_seconds']/60 for r in rows if r['generation']['elapsed_seconds'] is not None]))} | "
            f"{fmt(median([r['generation']['overall_tokens'] for r in rows]), 0)} | "
            f"{sum(r['acceptance_passed'] for r in sruns)}/{len(sruns)} | "
            f"{sum(r['comparison_verdict']=='EQUIVALENT' for r in sruns)} | "
            f"{sum(r['comparison_verdict']=='CANDIDATE_WEAKER' for r in sruns)} | "
            f"{fmt(median([r['active_seconds']/60 for r in sruns]))} | "
            f"{fmt(median([r['tokens']['total_tokens'] for r in sruns]), 0)} |"
        )
    lines += ["", "## Generation role cost (tier medians)", "",
              "| Tier | Designer min | Model min | Visualization min | Designer tokens | Model tokens | Visualization tokens |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for tier in TIERS:
        rows = [row for row in campaign if row["difficulty"] == tier]
        values = []
        for role in ("designer", "model", "visualization"):
            values.append(fmt(median([r["generation"]["agents"][role]["wall_seconds"]/60
                                      for r in rows if r["generation"]["agents"][role]["wall_seconds"] is not None])))
        for role in ("designer", "model", "visualization"):
            values.append(fmt(median([r["generation"]["agents"][role]["input_tokens"]
                                      + r["generation"]["agents"][role]["output_tokens"] for r in rows]), 0))
        lines.append(f"| {tier.title()} | " + " | ".join(values) + " |")
    lines += ["", "## Terra outcome summary", "",
              "| Verdict | N | Gate-qualified | Controller timeout | Median min | Median input+output tokens | Median added lines | Median proofs | Median verifier sec |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    all_scp = list(scp.values())
    for value in VERDICTS:
        rows = [row for row in all_scp if row["comparison_verdict"] == value]
        lines.append(
            f"| {value.replace('_', ' ').title()} | {len(rows)} | "
            f"{sum(r['acceptance_passed'] for r in rows)} | {sum(r['timed_out'] for r in rows)} | "
            f"{fmt(median([r['active_seconds']/60 for r in rows]))} | "
            f"{fmt(median([r['tokens']['total_tokens'] for r in rows]), 0)} | "
            f"{fmt(median([r['candidate']['added_nonblank_lines'] for r in rows]))} | "
            f"{fmt(median([r['proofs']['proof_count'] for r in rows]))} | "
            f"{fmt(median([r['proofs']['verification_seconds'] for r in rows]))} |"
        )
    lines += ["", "## Poolside outcome summary", "",
              "| Verdict | N | Gate-qualified | Median min | Median input+output tokens |",
              "|---|---:|---:|---:|---:|"]
    all_poolside = list(poolside.values())
    for value in VERDICTS:
        rows = [row for row in all_poolside if row["comparison_verdict"] == value]
        lines.append(
            f"| {value.replace('_', ' ').title()} | {len(rows)} | "
            f"{sum(r['gate_qualified'] for r in rows)} | "
            f"{fmt(median([r['active_seconds']/60 for r in rows]))} | "
            f"{fmt(median([r['tokens']['total_tokens'] for r in rows]), 0)} |"
        )
    lines += ["", "## Accept-gate failures (nonexclusive)", "",
              "| Gate | Failed runs |", "|---|---:|"]
    for gate in ("tipe", "codegen", "component_logika", "integration_logika"):
        lines.append(f"| {gate} | {sum(not r['gate_passes'].get(gate, False) for r in all_scp)} |")
    lines += ["", "## Controller and checker status", "",
              f"- Controller-completed: {sum(not r['timed_out'] for r in all_scp)}",
              f"- Controller timeouts: {sum(r['timed_out'] for r in all_scp)}",
              f"- Runs containing at least one timed-out atomic VC: {sum(r['checker_timeout'] for r in all_scp)}",
              f"- Runs containing a Logika proof-tool failure diagnostic: {sum(r['logika_bug'] for r in all_scp)}",
              "", "## Replicate outcome matrix", "",
              "Rows are replicate 1; columns are replicate 2. Verdicts other than equivalent or weaker are grouped as Other.", "",
              "| R1 \\ R2 | Equivalent | Weaker | Other |", "|---|---:|---:|---:|"]
    pairs = defaultdict(dict)
    generation_by_id = {row["dataset_id"]: row for row in campaign}
    for row in campaign:
        pairs[(row["family"], row["difficulty"])][row["replicate"]] = scp[row["dataset_id"]]
    categories = ("Equivalent", "Weaker", "Other")
    def category(row):
        return "Equivalent" if row["comparison_verdict"] == "EQUIVALENT" else (
            "Weaker" if row["comparison_verdict"] == "CANDIDATE_WEAKER" else "Other")
    matrix = Counter((category(pair[1]), category(pair[2])) for pair in pairs.values())
    for row_category in categories:
        lines.append(f"| {row_category} | " + " | ".join(
            str(matrix[(row_category, col_category)]) for col_category in categories) + " |")
    lines += ["", "## Measurement caveats", "",
              "- All reported generation timing covers the 48 seed-derived campaign instances.",
              "- Generation token `overall` is provider-reported input plus output. Reasoning output is a subset of output.",
              "- Comparative SCP total tokens are provider input plus output for both systems; cached and reasoning subsets are not added again.",
              "- Poolside uses a three-hour active-time cutoff; Terra uses one hour. Poolside conservative timing upper bounds are retained as upper bounds.",
              "- Checker stage totals exclude the duplicative `backend-total` event. Resident proof requests and retries are combined.",
              "- Gate-failure counts are nonexclusive: one run may fail multiple independent gates.",
              "- Relationships are descriptive for these 48 instances; no plot establishes causality or population-level statistical significance.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
